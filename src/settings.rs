//! The trusted systemd.nspawn(5) settings file nspawn keeps for every machine it manages.
//! The systemd-nspawn@.service template runs with --settings=override, so these values win
//! over its command line.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

use crate::oci::{Mode, RunSpec};

pub const SETTINGS_DIR: &str = "/etc/systemd/nspawn";

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, clap::ValueEnum)]
#[serde(rename_all = "lowercase")]
pub enum Network {
    /// The nspawn bridge (docker0 style): fixed address, NAT, published ports, names of
    /// the other machines. Needs nothing from the host's own network manager.
    Bridge,
    /// A virtual ethernet pair configured by systemd-networkd on the host.
    Veth,
    /// Share the host's network namespace, like docker run --network host.
    Host,
}

pub struct MachineSettings<'a> {
    pub name: &'a str,
    /// mstack images: boot with managed user namespaces instead of the template's -U.
    pub managed_userns: bool,
    pub mode: Mode,
    pub run: &'a RunSpec,
    /// Replaces the image's command for app machines (nspawn start NAME -- CMD).
    pub command_override: Option<&'a [String]>,
    pub network: Network,
    /// Bridge networking: the bridge to join and the directory with the machine's
    /// generated host0.network and hosts files.
    pub bridge: Option<BridgeMount<'a>>,
}

pub struct BridgeMount<'a> {
    pub bridge: &'a str,
    pub files: &'a Path,
}

pub fn path(name: &str) -> PathBuf {
    Path::new(SETTINGS_DIR).join(format!("{name}.nspawn"))
}

pub fn render(s: &MachineSettings) -> String {
    let mut out = format!(
        "# Generated by nspawn for image {}; do not edit.\n[Exec]\n",
        s.name
    );
    if s.managed_userns {
        out.push_str("PrivateUsers=managed\n");
    }
    match s.mode {
        Mode::Boot => out.push_str("Boot=yes\n"),
        Mode::App => {
            out.push_str("Boot=no\nProcessTwo=yes\n");
            let command: &[String] = s.command_override.unwrap_or(&s.run.command);
            if !command.is_empty() {
                let quoted: Vec<String> = command.iter().map(|a| quote(a)).collect();
                out.push_str(&format!("Parameters={}\n", quoted.join(" ")));
            }
            for var in &s.run.env {
                out.push_str(&format!("Environment={}\n", quote(var)));
            }
            if let Some(dir) = &s.run.working_dir {
                out.push_str(&format!("WorkingDirectory={dir}\n"));
            }
            match &s.run.user {
                Some(user) if !user.chars().all(|c| c.is_ascii_digit() || c == ':') => {
                    out.push_str(&format!("User={user}\n"));
                }
                _ => {}
            }
            let signal = s.run.stop_signal.as_deref().unwrap_or("SIGTERM");
            out.push_str(&format!("KillSignal={signal}\n"));
        }
    }
    match s.network {
        Network::Host => out.push_str("\n[Network]\nVirtualEthernet=no\n"),
        Network::Bridge => {
            if let Some(b) = &s.bridge {
                let files = b.files.display();
                out.push_str(&format!(
                    "\n[Network]\nBridge={}\n\n[Files]\nBindReadOnly={files}/host0.network:/run/systemd/network/10-host0.network\nBindReadOnly={files}/hosts:/etc/hosts\n",
                    b.bridge
                ));
            }
        }
        Network::Veth => {}
    }
    out
}

/// Writes the file when it differs from what is there.
pub fn write(s: &MachineSettings) -> Result<()> {
    let path = path(s.name);
    let wanted = render(s);
    if fs::read_to_string(&path)
        .map(|current| current == wanted)
        .unwrap_or(false)
    {
        return Ok(());
    }
    fs::create_dir_all(SETTINGS_DIR).with_context(|| format!("creating {SETTINGS_DIR}"))?;
    fs::write(&path, wanted).with_context(|| format!("writing {}", path.display()))
}

pub fn remove(name: &str) {
    let _ = fs::remove_file(path(name));
}

/// Quotes one argument the way systemd's config parser expects: double quotes with
/// backslash escapes when the argument has whitespace, quotes or backslashes.
pub fn quote(arg: &str) -> String {
    if !arg.is_empty()
        && !arg
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '"' | '\'' | '\\'))
    {
        return arg.to_string();
    }
    let mut out = String::from("\"");
    for c in arg.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(quote("nginx"), "nginx");
        assert_eq!(quote("daemon off;"), "\"daemon off;\"");
        assert_eq!(quote("a\"b"), "\"a\\\"b\"");
        assert_eq!(quote(""), "\"\"");
        assert_eq!(quote("PATH=/usr/bin"), "PATH=/usr/bin");
    }

    #[test]
    fn renders_boot_and_app_machines() {
        let run = RunSpec::default();
        let boot = render(&MachineSettings {
            name: "fedora-44",
            managed_userns: true,
            mode: Mode::Boot,
            run: &run,
            command_override: None,
            network: Network::Veth,
            bridge: None,
        });
        assert_eq!(boot, "# Generated by nspawn for image fedora-44; do not edit.\n[Exec]\nPrivateUsers=managed\nBoot=yes\n");

        let bridged = render(&MachineSettings {
            name: "fedora-44",
            managed_userns: false,
            mode: Mode::Boot,
            run: &run,
            command_override: None,
            network: Network::Bridge,
            bridge: Some(BridgeMount {
                bridge: "nspawn0",
                files: Path::new("/var/lib/nspawn/machines/fedora-44"),
            }),
        });
        assert!(bridged.contains("Boot=yes\n\n[Network]\nBridge=nspawn0\n\n[Files]\n"));
        assert!(bridged.contains("BindReadOnly=/var/lib/nspawn/machines/fedora-44/host0.network:/run/systemd/network/10-host0.network\n"));
        assert!(
            bridged.ends_with("BindReadOnly=/var/lib/nspawn/machines/fedora-44/hosts:/etc/hosts\n")
        );

        let run = RunSpec {
            command: vec!["nginx".into(), "-g".into(), "daemon off;".into()],
            env: vec!["PATH=/usr/bin".into(), "GREETING=hello world".into()],
            working_dir: Some("/srv".into()),
            user: Some("nginx".into()),
            stop_signal: Some("SIGQUIT".into()),
        };
        let app = render(&MachineSettings {
            name: "web",
            managed_userns: false,
            mode: Mode::App,
            run: &run,
            command_override: None,
            network: Network::Host,
            bridge: None,
        });
        assert!(app.contains("Boot=no\nProcessTwo=yes\n"));
        assert!(app.contains("Parameters=nginx -g \"daemon off;\"\n"));
        assert!(app.contains("Environment=PATH=/usr/bin\nEnvironment=\"GREETING=hello world\"\n"));
        assert!(app.contains("WorkingDirectory=/srv\nUser=nginx\nKillSignal=SIGQUIT\n"));
        assert!(app.ends_with("[Network]\nVirtualEthernet=no\n"));

        let numeric_user = RunSpec {
            user: Some("1000:1000".into()),
            ..RunSpec::default()
        };
        let text = render(&MachineSettings {
            name: "x",
            managed_userns: false,
            mode: Mode::App,
            run: &numeric_user,
            command_override: Some(&["/bin/sleep".to_string(), "infinity".to_string()]),
            network: Network::Veth,
            bridge: None,
        });
        assert!(!text.contains("User="));
        assert!(text.contains("Parameters=/bin/sleep infinity\nKillSignal=SIGTERM\n"));
        assert!(!text.contains("[Network]"));
    }
}
