//! The trusted systemd.nspawn(5) settings file nspawn keeps for every machine it manages.
//! The systemd-nspawn@.service template runs with --settings=override, so these values win
//! over its command line.

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde::{Deserialize, Serialize};

use crate::oci::{Mode, RunSpec};
use crate::systemd::Systemd;

pub const SETTINGS_DIR: &str = "/etc/systemd/nspawn";

/// The settings key NamespacePath= exists since this systemd version.
pub const NAMESPACE_PATH_SETTING_SINCE: u32 = 259;

/// How the network namespace prepared on the host for an app on the bridge reaches
/// nspawn.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NamespaceRoute {
    /// NamespacePath= in the settings file.
    Settings,
    /// --network-namespace-path= on the unit's command line, rewritten from the argv
    /// systemd has for the unit: older systemd has no settings key for it.
    CommandLine(Vec<String>),
}

/// Apps on the bridge before systemd 259 need the command line; everything else the
/// settings file.
pub async fn namespace_route(
    sd: &Systemd,
    name: &str,
    mode: Mode,
    network: Network,
) -> Result<NamespaceRoute> {
    if mode != Mode::App || network != Network::Bridge {
        return Ok(NamespaceRoute::Settings);
    }
    if sd
        .major()
        .await
        .is_some_and(|major| major >= NAMESPACE_PATH_SETTING_SINCE)
    {
        return Ok(NamespaceRoute::Settings);
    }
    let unit = format!("systemd-nspawn@{name}.service");
    Ok(NamespaceRoute::CommandLine(sd.exec_start(&unit).await?))
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, clap::ValueEnum)]
#[serde(rename_all = "lowercase")]
pub enum Network {
    /// The nspawn bridge (docker0 style): fixed address, NAT, published ports, names of
    /// the other machines. Needs nothing from the host's own network manager.
    Bridge,
    /// A virtual ethernet pair configured by systemd-networkd on the host.
    Veth,
    /// Share the host's network namespace, like docker run --network host.
    Host,
}

pub struct MachineSettings<'a> {
    pub name: &'a str,
    /// mstack images: boot with managed user namespaces instead of the template's -U.
    pub managed_userns: bool,
    pub mode: Mode,
    /// Working directory, user, environment and stop signal of the image.
    pub run: &'a RunSpec,
    /// What an app machine runs: entrypoint and cmd, overrides applied.
    pub command: &'a [String],
    /// Environment given with -e, after the image's.
    pub extra_env: &'a [String],
    /// Volumes, resolved to host paths.
    pub binds: &'a [Bind],
    /// Directory with the units that make a booted machine wait for its volumes (see
    /// `volume_wait_units`), when it has any.
    pub volume_units: Option<&'a Path>,
    pub network: Network,
    /// Bridge networking: the bridge to join and the directory with the machine's
    /// generated host0.network and hosts files.
    pub bridge: Option<BridgeMount<'a>>,
}

pub struct BridgeMount<'a> {
    pub bridge: &'a str,
    pub files: &'a Path,
}

/// A volume ready to mount.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Bind {
    pub source: PathBuf,
    pub target: String,
    pub read_only: bool,
}

pub fn path(name: &str) -> PathBuf {
    Path::new(SETTINGS_DIR).join(format!("{name}.nspawn"))
}

#[cfg(test)]
pub fn render(s: &MachineSettings) -> String {
    render_with(s, &NamespaceRoute::Settings)
}

pub fn render_with(s: &MachineSettings, route: &NamespaceRoute) -> String {
    let mut out = format!(
        "# Generated by nspawn for image {}; do not edit.\n[Exec]\n",
        s.name
    );
    let mut private_users = true;
    if s.managed_userns {
        out.push_str("PrivateUsers=managed\n");
    } else if s.mode == Mode::App && s.network == Network::Bridge && s.bridge.is_some() {
        // A user namespace cannot join the network namespace prepared on the host
        // (EPERM: it belongs to the initial user namespace), so app machines on the
        // bridge run without one, as docker does.
        out.push_str("PrivateUsers=no\n");
        private_users = false;
    }
    match s.mode {
        Mode::Boot => out.push_str("Boot=yes\n"),
        Mode::App => {
            out.push_str("Boot=no\nProcessTwo=yes\n");
            if !s.command.is_empty() {
                let quoted: Vec<String> = s.command.iter().map(|a| quote(a)).collect();
                out.push_str(&format!("Parameters={}\n", quoted.join(" ")));
            }
            // A later assignment of the same variable wins, so -e comes after the image's.
            for var in s.run.env.iter().chain(s.extra_env) {
                out.push_str(&format!("Environment={}\n", quote(var)));
            }
            if let Some(dir) = &s.run.working_dir {
                out.push_str(&format!("WorkingDirectory={dir}\n"));
            }
            // nspawn's User= takes a name or a uid; the gid of docker's "uid:gid" form has
            // no counterpart and is left to the image's passwd.
            if let Some(user) = &s.run.user {
                let user = user.split_once(':').map(|(u, _)| u).unwrap_or(user);
                if !user.is_empty() {
                    out.push_str(&format!("User={user}\n"));
                }
            }
            // What nspawn forwards to the stub init when the unit is stopped: a poweroff
            // request, which the stub answers with SIGTERM to the program and waits. The
            // image's own stop signal is what `nspawn stop` sends to the program itself.
            out.push_str("KillSignal=SIGRTMIN+4\n");
        }
    }
    let mut files: Vec<String> = Vec::new();
    match s.network {
        Network::Host => out.push_str("\n[Network]\nVirtualEthernet=no\n"),
        Network::Bridge => {
            if let Some(b) = &s.bridge {
                let dir = b.files.display();
                match s.mode {
                    // systemd-networkd inside configures host0 from the mounted file.
                    Mode::Boot => {
                        out.push_str(&format!("\n[Network]\nBridge={}\n", b.bridge));
                        files.push(format!(
                            "BindReadOnly={dir}/host0.network:/run/systemd/network/10-host0.network"
                        ));
                        files.push(format!("BindReadOnly={dir}/hosts:/etc/hosts"));
                    }
                    // Nothing inside to configure anything: the namespace comes ready.
                    Mode::App => {
                        if *route == NamespaceRoute::Settings {
                            out.push_str(&format!(
                                "\n[Network]\nNamespacePath={}\n",
                                crate::bridge::netns_path(s.name)
                            ));
                        }
                        files.push(format!("BindReadOnly={dir}/hosts:/etc/hosts"));
                        files.push(format!("BindReadOnly={dir}/resolv.conf:/etc/resolv.conf"));
                    }
                }
            }
        }
        Network::Veth => {}
    }
    // Under managed user namespaces nspawn cannot idmap binds; those volumes are attached
    // from the host once the machine runs (see volmount). Every booted machine with
    // volumes gets the unit that holds local-fs.target until they are all there: the same
    // guarantee whatever the backend, and on overlay and flat the binds below make them
    // present before the init even runs.
    let rendered_binds: &[Bind] = if s.managed_userns { &[] } else { s.binds };
    if s.mode == Mode::Boot && !s.binds.is_empty() {
        if let Some(units) = s.volume_units {
            let units = units.display();
            files.push(format!(
                "BindReadOnly={units}/nspawn-volumes.service:/run/systemd/system/nspawn-volumes.service"
            ));
            files.push(format!(
                "BindReadOnly={units}/nspawn-volumes.conf:/run/systemd/system/local-fs.target.d/nspawn-volumes.conf"
            ));
        }
    }
    for bind in rendered_binds {
        // With private users the host's uid 0 is nobody inside; idmap makes root inside
        // the owner of what it writes, as docker users expect.
        let options = if private_users { ":idmap" } else { "" };
        files.push(format!(
            "{}={}:{}{options}",
            if bind.read_only {
                "BindReadOnly"
            } else {
                "Bind"
            },
            bind.source.display(),
            bind.target
        ));
    }
    if !files.is_empty() {
        out.push_str("\n[Files]\n");
        for line in files {
            out.push_str(&line);
            out.push('\n');
        }
    }
    out
}

/// The units mounted into a booted machine so that its boot waits for its volumes:
/// (service, drop-in for local-fs.target).
pub fn volume_wait_units(targets: &[String]) -> (String, String) {
    let list = targets
        .iter()
        .map(|t| quote(t))
        .collect::<Vec<_>>()
        .join(" ");
    let service = format!(
        "# Generated by nspawn; do not edit.\n[Unit]\nDescription=Wait for the volumes nspawn attaches from the host\nDefaultDependencies=no\nBefore=local-fs.target\n\n[Service]\nType=oneshot\nRemainAfterExit=yes\nExecStart=/bin/sh -c 'for p in {list}; do i=0; until mountpoint -q \"$p\"; do i=$((i+1)); if [ $i -ge 2400 ]; then echo \"$p: volume not attached\" >&2; exit 1; fi; sleep 0.05; done; done'\n"
    );
    let dropin = "# Generated by nspawn; do not edit.\n[Unit]\nWants=nspawn-volumes.service\nAfter=nspawn-volumes.service\n".to_string();
    (service, dropin)
}

/// The drop-in that makes the machine's unit call nspawn around its life: the network is
/// prepared before it starts, ports are published once it runs and everything is released
/// however it ends, whether it was started by nspawn, machinectl or at boot. Returns
/// whether the file changed (a daemon-reload is then due).
pub fn write_hooks(
    name: &str,
    config: &crate::config::Config,
    route: &NamespaceRoute,
) -> Result<bool> {
    let exe = std::env::current_exe().context("locating the nspawn binary")?;
    let exe = replaced_binary(&exe)
        .filter(|path| path.exists())
        .unwrap_or(exe);
    let exe = fs::canonicalize(&exe).unwrap_or(exe);
    let mut command = quote(&exe.to_string_lossy());
    if let Some(path) = &config.config_path {
        command.push_str(" --config ");
        command.push_str(&quote(&path.to_string_lossy()));
    }
    let mut text = format!(
        "# Generated by nspawn; do not edit.\n[Service]\nExecStartPre={command} network prepare %i\nExecStartPost={command} network publish %i\nExecStopPost=-{command} network release %i\n"
    );
    if let NamespaceRoute::CommandLine(argv) = route {
        text.push_str(&exec_start_override(argv, name));
    }
    let dir = crate::backend::dropin_dir(name);
    let path = dir.join("nspawn-hooks.conf");
    if fs::read_to_string(&path)
        .map(|current| current == text)
        .unwrap_or(false)
    {
        return Ok(false);
    }
    fs::create_dir_all(&dir).with_context(|| format!("creating {}", dir.display()))?;
    fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
    Ok(true)
}

/// The ExecStart= lines that put the namespace on the unit's command line: the argv as
/// loaded, without the options that conflict with --network-namespace-path= (only their
/// `--option=value` form is recognised) and with that option added. Applied to its own
/// result it gives the same lines again.
pub fn exec_start_override(argv: &[String], name: &str) -> String {
    const CONFLICTING: &[&str] = &[
        "--network-veth",
        "-n",
        "--network-namespace-path",
        "--network-bridge",
        "--network-zone",
        "--network-interface",
        "--network-macvlan",
        "--network-ipvlan",
        "--network-veth-extra",
    ];
    let kept: Vec<String> = argv
        .iter()
        .filter(|arg| {
            !CONFLICTING
                .iter()
                .any(|option| arg == option || arg.starts_with(&format!("{option}=")))
        })
        .map(|arg| unit_quote(arg))
        .collect();
    format!(
        "ExecStart=\nExecStart={} --network-namespace-path={}\n",
        kept.join(" "),
        unit_quote(&crate::bridge::netns_path(name))
    )
}

/// One argument of an ExecStart= line: `%` starts a specifier and is doubled, and
/// anything beyond plain characters goes in double quotes with backslash escapes.
pub fn unit_quote(arg: &str) -> String {
    let plain = !arg.is_empty()
        && arg
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || "-_.:/=@+,".contains(c));
    if plain {
        return arg.to_string();
    }
    let mut quoted = String::from("\"");
    for c in arg.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '%' => quoted.push_str("%%"),
            _ => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

/// Writes the file when it differs from what is there.
pub fn write(s: &MachineSettings, route: &NamespaceRoute) -> Result<()> {
    let path = path(s.name);
    let wanted = render_with(s, route);
    if fs::read_to_string(&path)
        .map(|current| current == wanted)
        .unwrap_or(false)
    {
        return Ok(());
    }
    fs::create_dir_all(SETTINGS_DIR).with_context(|| format!("creating {SETTINGS_DIR}"))?;
    fs::write(&path, wanted).with_context(|| format!("writing {}", path.display()))
}

pub fn remove(name: &str) {
    let _ = fs::remove_file(path(name));
}

/// Quotes one argument the way systemd's config parser (config_parse_strv) reads it:
/// quotes group, backslashes are kept literally and never escape anything, and adjacent
/// quoted pieces join into one word. So the whole argument goes in single quotes, and
/// each single quote it contains rides in double quotes between two such pieces.
pub fn quote(arg: &str) -> String {
    if !arg.is_empty()
        && !arg
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '"' | '\'' | '\\'))
    {
        return arg.to_string();
    }
    let mut out = String::new();
    for (i, piece) in arg.split('\'').enumerate() {
        if i > 0 {
            out.push_str("\"'\"");
        }
        if !piece.is_empty() {
            out.push('\'');
            out.push_str(piece);
            out.push('\'');
        }
    }
    if out.is_empty() {
        "''".to_string()
    } else {
        out
    }
}

/// Once the file a process runs has been replaced, as a package upgrade does,
/// /proc/self/exe (which is what current_exe reads) reports "<path> (deleted)". The
/// hooks must name the path itself, where the new file sits, or every machine started
/// afterwards fails to execute them.
fn replaced_binary(exe: &Path) -> Option<PathBuf> {
    exe.to_str()?.strip_suffix(" (deleted)").map(PathBuf::from)
}

