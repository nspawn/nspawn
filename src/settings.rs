    #[test]
    fn the_hooks_drop_in_carries_the_policy_and_the_limits() {
        let command = "/usr/bin/nspawn";
        let plain = render_hooks(
            command,
            "web",
            &NamespaceRoute::Settings,
            None,
            Restart::No,
            &Limits::default(),
        );
        assert_eq!(
            plain,
            "# Generated by nspawn; do not edit.\n[Service]\nExecStartPre=/usr/bin/nspawn network prepare %i\nExecStartPost=/usr/bin/nspawn network publish %i\nExecStopPost=-/usr/bin/nspawn network release %i\nLogRateLimitIntervalSec=0\n",
            "a booted machine without a policy or limits: the hooks alone"
        );
        let on_failure = render_hooks(
            command,
            "web",
            &NamespaceRoute::Settings,
            None,
            Restart::OnFailure,
            &Limits::default(),
        );
        assert!(on_failure.starts_with(
            "# Generated by nspawn; do not edit.\n[Unit]\nStartLimitIntervalSec=0\n[Service]\n"
        ));
        assert!(on_failure.ends_with(
            "Restart=on-failure\nRestartSec=1s\nRestartSteps=5\nRestartMaxDelaySec=30s\n"
        ));
        for policy in [Restart::Always, Restart::UnlessStopped] {
            let text = render_hooks(
                command,
                "web",
                &NamespaceRoute::Settings,
                None,
                policy,
                &Limits::default(),
            );
            assert!(text.contains("\nRestart=always\n"));
        }
        let limited = render_hooks(
            command,
            "web",
            &NamespaceRoute::Settings,
            None,
            Restart::No,
            &Limits {
                memory: 64 << 20,
                milli_cpus: 500,
                pids: 100,
            },
        );
        assert!(!limited.contains("[Unit]"));
        assert!(limited
            .ends_with("MemoryMax=67108864\nMemorySwapMax=67108864\nCPUQuota=50%\nTasksMax=100\n"));
        let only_cpus = render_hooks(
            command,
            "web",
            &NamespaceRoute::Settings,
            None,
            Restart::No,
            &Limits {
                memory: 0,
                milli_cpus: 333,
                pids: 0,
            },
        );
        assert!(
            only_cpus.ends_with("network release %i\nLogRateLimitIntervalSec=0\nCPUQuota=33.3%\n")
        );
        let argv: Vec<String> = [
            "systemd-nspawn",
            "--quiet",
            "--network-veth",
            "--machine=web",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect();
        let old_systemd = render_hooks(
            command,
            "web",
            &NamespaceRoute::CommandLine(argv.clone()),
            Some(&argv),
            Restart::Always,
            &Limits::default(),
        );
        assert!(old_systemd.ends_with(&exec_start_override(command, &argv, "web", true)));
        assert!(old_systemd.contains("RestartMaxDelaySec=30s\nExecStart="));
        let app = render_hooks(
            command,
            "web",
            &NamespaceRoute::Settings,
            Some(&argv),
            Restart::No,
            &Limits::default(),
        );
        assert!(app.ends_with(&exec_start_override(command, &argv, "web", false)));
    }
