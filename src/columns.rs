//! Columns text takes on a terminal, counted where text is lined up or cut by the
//! formats --format takes. docker/cli v29.8.2 cuts with formatter.Ellipsis, whose
//! widths are the East Asian Width of golang.org/x/text/width v0.42.0 (Unicode 15.0.0
//! under Go 1.26), and lines up tables with its fork of text/tabwriter, which measures
//! cells with go-runewidth v0.0.29: per grapheme cluster, the widths of its characters
//! added up to at most two. The tables below are the answers of those functions for
//! every code point, from running them; their ranges are inclusive.

use std::{cmp::Ordering, sync::OnceLock};

use unicode_segmentation::UnicodeSegmentation;

/// Columns of `c` to Ellipsis: two for wide and fullwidth forms, one for any other
/// character, control characters and combining marks included.
pub fn ellipsis_width(c: char) -> usize {
    if within(WIDE, c) {
        2
    } else {
        1
    }
}

/// go-runewidth's StringWidth in the locale of this process.
pub fn string_width(s: &str) -> usize {
    string_width_in(s, east_asian())
}

fn string_width_in(s: &str, east_asian: bool) -> usize {
    if s.is_ascii() {
        return s.bytes().filter(|&b| b >= 0x20 && b != 0x7f).count();
    }
    s.graphemes(true)
        .map(|cluster| {
            cluster
                .chars()
                .map(|c| rune_width(c, east_asian))
                .sum::<usize>()
                .min(2)
        })
        .sum()
}

/// go-runewidth's RuneWidth, which takes an emoji whose width is ambiguous as one column.
fn rune_width(c: char, east_asian: bool) -> usize {
    let (zero, two) = match east_asian {
        false => (ZERO, TWO),
        true => (EA_ZERO, EA_TWO),
    };
    if within(zero, c) {
        0
    } else if within(two, c) {
        2
    } else {
        1
    }
}

fn within(table: &[(u32, u32)], c: char) -> bool {
    let c = c as u32;
    table
        .binary_search_by(|&(first, last)| {
            if last < c {
                Ordering::Less
            } else if first > c {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether go-runewidth counts ambiguous characters as two columns: RUNEWIDTH_EASTASIAN
/// says so when set ("1"), else the locale does.
fn east_asian() -> bool {
    static EAST_ASIAN: OnceLock<bool> = OnceLock::new();
    *EAST_ASIAN.get_or_init(|| {
        let var = |name: &str| {
            std::env::var_os(name)
                .map(|value| value.to_string_lossy().into_owned())
                .unwrap_or_default()
        };
        match var("RUNEWIDTH_EASTASIAN").as_str() {
            "" => {
                let locale = ["LC_ALL", "LC_CTYPE", "LANG"]
                    .into_iter()
                    .map(var)
                    .find(|locale| !locale.is_empty())
                    .unwrap_or_default();
                east_asian_locale(&locale)
            }
            set => set == "1",
        }
    })
}

/// IsEastAsian of go-runewidth's runewidth_posix.go: a Chinese, Japanese or Korean
/// locale, or a locale whose charset takes several bytes and is not UTF-8.
fn east_asian_locale(locale: &str) -> bool {
    let bytes = locale.as_bytes();
    if locale == "POSIX"
        || locale == "C"
        || (bytes.len() > 1 && bytes[0] == b'C' && matches!(bytes[1], b'.' | b'-'))
    {
        return false;
    }
    let mut charset = match locale_charset(locale) {
        "" => locale.to_lowercase(),
        charset => charset.to_lowercase(),
    };
    if charset.ends_with("@cjk_narrow") {
        return false;
    }
    if let Some(at) = charset.find('@') {
        charset.truncate(at);
    }
    let longest = match charset.as_str() {
        "utf-8" | "utf8" => 6,
        "jis" => 8,
        "eucjp" => 3,
        "euckr" | "euccn" | "sjis" | "cp932" | "cp51932" | "cp936" | "cp949" | "cp950" | "big5"
        | "gbk" | "gb2312" => 2,
        _ => 1,
    };
    longest > 1
        && (!charset.starts_with('u')
            || ["ja", "ko", "zh"]
                .iter()
                .any(|language| locale.starts_with(language)))
}

/// The charset of a locale named `ll.CHARSET` or `ll_CC.CHARSET` (a language of two or
/// three letters), or "" for any other name.
fn locale_charset(locale: &str) -> &str {
    let language = locale.bytes().take_while(u8::is_ascii_lowercase).count();
    if !(2..=3).contains(&language) {
        return "";
    }
    let mut rest = &locale[language..];
    let country = rest.as_bytes();
    if country.len() >= 3
        && country[0] == b'_'
        && country[1].is_ascii_uppercase()
        && country[2].is_ascii_uppercase()
    {
        rest = &rest[3..];
    }
    match rest.strip_prefix('.') {
        Some(charset) if !charset.is_empty() => charset,
        _ => "",
    }
}

