#!/bin/sh
# Writes src/compose/unicode.rs: the Unicode tables of the Go release docker compose
# builds with (its go.mod names it), as Go's unicode and strconv packages have them, for
# what compose and its libraries decide character by character: strconv.IsPrint (%q),
# unicode.IsLetter, IsDigit, IsNumber, IsSpace and ToLower; and the texts Go gives the errors of
# system calls, which its file errors print.
#
#   tests/compose/oracle.sh build              (once: fetches docker compose's source)
#   tests/compose/go-tables.sh
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
oracle="$root/target/compose-oracle"
[ -f "$oracle/src/go.mod" ] || { echo "run $here/oracle.sh build first" >&2; exit 1; }
go=$(awk '$1 == "go" { print $2; exit }' "$oracle/src/go.mod")
work=$(mktemp -d)
trap 'rm -r "$work"' EXIT

cat >"$work/main.go" <<'GO'
package main

import (
	"fmt"
	"runtime"
	"strconv"
	"strings"
	"syscall"
	"unicode"
)

// The runs of code points where a predicate holds, as (first, last) pairs.
func ranges(name string, holds func(rune) bool) {
	var pairs []string
	start := rune(-1)
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		in := r <= unicode.MaxRune && holds(r)
		if in && start < 0 {
			start = r
		}
		if !in && start >= 0 {
			pairs = append(pairs, fmt.Sprintf("(0x%x, 0x%x)", start, r-1))
			start = -1
		}
	}
	table(name, "(u32, u32)", pairs)
}

func table(name, kind string, items []string) {
	fmt.Printf("pub const %s: &[%s] = &[\n", name, kind)
	for i := 0; i < len(items); i += 6 {
		end := min(i+6, len(items))
		fmt.Printf("    %s,\n", strings.Join(items[i:end], ", "))
	}
	fmt.Printf("];\n\n")
}

func main() {
	fmt.Printf("//! Generated by tests/compose/go-tables.sh from %s (Unicode %s); do not edit.\n\n",
		runtime.Version(), unicode.Version)
	fmt.Printf("#![allow(clippy::unreadable_literal)]\n\n")
	ranges("PRINT", strconv.IsPrint)
	ranges("LETTER", unicode.IsLetter)
	ranges("DIGIT", unicode.IsDigit)
	ranges("NUMBER", unicode.IsNumber)
	ranges("SPACE", unicode.IsSpace)
	// ToLower, as (first, last, stride, delta): from first to last, every stride-th
	// code point maps to itself plus delta.
	var runs []string
	type run struct{ first, last, stride, delta int32 }
	var cur *run
	flush := func() {
		if cur != nil {
			runs = append(runs, fmt.Sprintf("(0x%x, 0x%x, %d, %d)", cur.first, cur.last, cur.stride, cur.delta))
			cur = nil
		}
	}
	for r := rune(0); r <= unicode.MaxRune; r++ {
		l := unicode.ToLower(r)
		if l == r {
			continue
		}
		d := l - r
		if cur != nil && cur.delta == d && (r-cur.last == cur.stride || (cur.first == cur.last && r-cur.last <= 2)) {
			cur.stride = r - cur.last
			cur.last = r
			continue
		}
		flush()
		cur = &run{r, r, 1, d}
	}
	flush()
	table("LOWER", "(u32, u32, u32, i32)", runs)
	// syscall.Errno's texts, by number, as far as Go names them.
	var errnos []string
	for n := 0; n < 134; n++ {
		errnos = append(errnos, strconv.Quote(syscall.Errno(n).Error()))
	}
	table("ERRNO", "&str", errnos)
}
GO

docker run --rm --network none --memory 2g --user "$(id -u):$(id -g)" \
    -v "$work:/src" -w /src -e HOME=/tmp -e GOCACHE=/tmp/gocache -e GOTOOLCHAIN=local \
    "golang:${go%.*}" go run main.go >"$root/src/compose/unicode.rs"
echo "wrote src/compose/unicode.rs"
